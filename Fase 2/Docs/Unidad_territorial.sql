CREATE TABLE "junta" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(120) NOT NULL,
  "unidad_vecinal" varchar(60) NOT NULL,
  "comuna" varchar(60) NOT NULL,
  "direccion_sede" varchar(150),
  "logo_url" varchar(255),
  "correo_contacto" varchar(120),
  "creado_en" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "directorio_integrante" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "junta_id" int NOT NULL,
  "usuario_id" int NOT NULL,
  "cargo" cargo_directorio NOT NULL,
  "fecha_inicio" date NOT NULL,
  "fecha_fin" date
);

CREATE TABLE "usuario" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "junta_id" int NOT NULL,
  "rut" varchar(12) UNIQUE NOT NULL,
  "nombres" varchar(80) NOT NULL,
  "apellidos" varchar(80) NOT NULL,
  "fecha_nacimiento" date NOT NULL,
  "direccion" varchar(150) NOT NULL,
  "correo" varchar(120) UNIQUE NOT NULL,
  "telefono" varchar(20),
  "password_hash" varchar(255) NOT NULL,
  "rol" rol_usuario NOT NULL DEFAULT 'vecino',
  "estado" estado_usuario NOT NULL DEFAULT 'pendiente',
  "creado_en" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "token_recuperacion" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL,
  "token_hash" varchar(255) UNIQUE NOT NULL,
  "expira_en" timestamp NOT NULL,
  "usado_en" timestamp,
  "creado_en" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "sesion" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL,
  "token_hash" varchar(255) UNIQUE NOT NULL,
  "expira_en" timestamp NOT NULL,
  "creado_en" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "documento_verificacion" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL,
  "tipo" tipo_documento NOT NULL,
  "ruta" varchar(255) NOT NULL,
  "estado" estado_documento NOT NULL DEFAULT 'pendiente',
  "motivo_rechazo" text,
  "fecha_subida" timestamp NOT NULL DEFAULT (now()),
  "revisado_por" int,
  "fecha_revision" timestamp
);

CREATE TABLE "solicitud_certificado" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL,
  "estado" estado_certificado NOT NULL DEFAULT 'pendiente',
  "folio" varchar(20) UNIQUE,
  "direccion_certificada" varchar(150),
  "fecha_solicitud" timestamp NOT NULL DEFAULT (now()),
  "fecha_emision" timestamp
);

CREATE TABLE "proyecto" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL,
  "titulo" varchar(150) NOT NULL,
  "descripcion" text NOT NULL,
  "presupuesto_estimado" int NOT NULL,
  "estado" estado_proyecto NOT NULL DEFAULT 'recibido',
  "fecha_postulacion" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "proyecto_adjunto" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "proyecto_id" int NOT NULL,
  "nombre_archivo" varchar(150) NOT NULL,
  "ruta" varchar(255) NOT NULL,
  "tipo_mime" varchar(80) NOT NULL,
  "tamano_bytes" int NOT NULL
);

CREATE TABLE "espacio" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "junta_id" int NOT NULL,
  "nombre" varchar(100) NOT NULL,
  "tipo" tipo_espacio NOT NULL,
  "descripcion" text,
  "activo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "reserva" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "espacio_id" int NOT NULL,
  "usuario_id" int NOT NULL,
  "inicio" timestamp NOT NULL,
  "fin" timestamp NOT NULL,
  "motivo" varchar(200),
  "estado" estado_reserva NOT NULL DEFAULT 'pendiente',
  "creado_en" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "actividad" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "junta_id" int NOT NULL,
  "creado_por" int NOT NULL,
  "titulo" varchar(150) NOT NULL,
  "descripcion" text,
  "lugar" varchar(150) NOT NULL,
  "fecha_hora" timestamp NOT NULL,
  "cupo_maximo" int NOT NULL,
  "estado" estado_actividad NOT NULL DEFAULT 'programada'
);

CREATE TABLE "inscripcion_actividad" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "actividad_id" int NOT NULL,
  "usuario_id" int NOT NULL,
  "estado" estado_inscripcion NOT NULL DEFAULT 'inscrito',
  "fecha_inscripcion" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "aviso" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "junta_id" int NOT NULL,
  "autor_id" int NOT NULL,
  "titulo" varchar(150) NOT NULL,
  "mensaje" text NOT NULL,
  "afiche_url" varchar(255),
  "fecha_creacion" timestamp NOT NULL DEFAULT (now()),
  "fecha_envio_correo" timestamp
);

CREATE TABLE "notificacion_enviada" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "aviso_id" int NOT NULL,
  "usuario_id" int NOT NULL,
  "canal" canal_notificacion NOT NULL,
  "estado" estado_notificacion NOT NULL DEFAULT 'enviado',
  "fecha_envio" timestamp NOT NULL DEFAULT (now()),
  "fecha_lectura" timestamp
);

CREATE TABLE "noticia" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "junta_id" int NOT NULL,
  "autor_id" int NOT NULL,
  "titulo" varchar(150) NOT NULL,
  "contenido" text NOT NULL,
  "imagen_url" varchar(255),
  "fecha_publicacion" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "historial_estado" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tipo" tipo_entidad NOT NULL,
  "entidad_id" int NOT NULL,
  "estado_anterior" varchar(30),
  "estado_nuevo" varchar(30) NOT NULL,
  "motivo" text,
  "responsable_id" int NOT NULL,
  "fecha" timestamp NOT NULL DEFAULT (now())
);

